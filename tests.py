"""Automatic tests for the whole project.

Usage:  python3 tests.py

1. The examples of the statement (exact output of main.py).
2. FIRST/FOLLOW and LR(0) states against values of the book.
3. Item 3: results of run_sdd.py (including the circular variant).
4. Cross-check: for several grammars, every string over the alphabet up to a
   given length is parsed and compared with the language generated by
   brute-force leftmost derivations (an oracle that does not use the parsers).
Only the standard library is used. The exit code is 0 when everything passes.
"""
import itertools
import os
import subprocess
import sys
from collections import deque

from grammar import parse_grammar, format_set
from ll1 import LL1
from slr import SLR1

HERE = os.path.dirname(os.path.abspath(__file__))
MENU = "Select a parser (T: for LL(1), B: for SLR(1), Q: quit):"
total = 0
failures = 0


def check(name, cond, detail=''):
    global total, failures
    total += 1
    if cond:
        print(f"  ok    {name}")
    else:
        failures += 1
        print(f"  FAIL  {name}  {detail}")


def run(script, stdin, *args):
    p = subprocess.run([sys.executable, os.path.join(HERE, script), *args],
                       input=stdin, capture_output=True, text=True,
                       cwd=HERE, timeout=120)
    return p.stdout


# ----------------------------------------------------------------------
def test_statement_examples():
    print("1. Examples of the statement (main.py)")
    out = run('main.py', "3\nS -> S+T T\nT -> T*F F\nF -> (S) i\n"
                         "i+i\n(i)\n(i+i)*i)\n\n")
    check("Example 1 (SLR(1) only)",
          out == "Grammar is SLR(1).\nyes\nyes\nno\n", repr(out))

    out = run('main.py', "3\nS -> AB\nA -> aA d\nB -> bBc e\n"
                         "T\nd\nadbc\na\n\nQ\n")
    check("Example 2 (both, parser T, then Q)",
          out == f"{MENU}\nyes\nyes\nno\n{MENU}\n", repr(out))

    out = run('main.py', "3\nS -> AB\nA -> aA d\nB -> bBc e\n"
                         "B\nd\nadbc\na\n\nQ\n")
    check("Example 2 with the SLR(1) parser",
          out == f"{MENU}\nyes\nyes\nno\n{MENU}\n", repr(out))

    out = run('main.py', "1\nS -> SS a\n")
    check("Example 3 (neither)",
          out == "Grammar is neither LL(1) nor SLR(1).\n", repr(out))

    out = run('main.py', "3\nS -> AaAb BbBa\nA -> e\nB -> e\nab\nba\na\n\n")
    check("LL(1) but not SLR(1)",
          out == "Grammar is LL(1).\nyes\nyes\nno\n", repr(out))

    out = run('main.py', "1\nS -> Sa b\nb\nbaa\nab\n\n")
    check("SLR(1) but not LL(1)",
          out == "Grammar is SLR(1).\nyes\nyes\nno\n", repr(out))

    out = run('main.py', "1\nS -> aSb e\nT\ne\nab\naabb\naab\n\nQ\n")
    check("Empty string is given as e",
          out == f"{MENU}\nyes\nyes\nyes\nno\n{MENU}\n", repr(out))

    out = run('main.py', "3\nS -> AB\nA -> aA d\nB -> bBc e\n", '--sets')
    expected = ("First(A) = {a, d}\nFirst(B) = {b, e}\nFirst(S) = {a, d}\n"
                "Follow(A) = {b, $}\nFollow(B) = {c, $}\nFollow(S) = {$}\n")
    check("--sets format (ASCII order, then e, then $)",
          out.startswith(expected), repr(out[:200]))

    out = run('main.py', "1\nS -> a\nT\na$\n\nQ\n")
    check("A string containing $ is rejected", "no" in out.split(), repr(out))


