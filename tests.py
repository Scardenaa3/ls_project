def last_line(out):
    lines = [x for x in out.strip().splitlines() if x.strip()]
    return lines[-1] if lines else ''


def test_sdd():
    print("3. Item 3 (run_sdd.py)")
    cases = [("7", 7), ("12", -1), ("1234", -2), ("9876543210", 5),
             ("905", 14), ("4172", 4 - 1 + 7 - 2)]
    for s, v in cases:
        for parser in ('ll1', 'slr1'):
            out = run('run_sdd.py', s + "\n\n", '--parser', parser)
            check(f"{s} -> S.v = {v} ({parser})",
                  last_line(out) == f"S.v = {v}", last_line(out))
    out = run('run_sdd.py', "12a\n\n")
    check("12a is not in the language", last_line(out) == "no", last_line(out))
    out = run('run_sdd.py', "\n")
    check("Empty line ends the input", out.strip() == '', repr(out))
    out = run('run_sdd.py', "12\n\n", '--circular')
    check("Circular variant is detected for 12", 'circular' in out, out[:200])
    out = run('run_sdd.py', "1\n\n", '--circular')
    check("Circular variant: one digit has no cycle",
          last_line(out) == "S.v = 1", last_line(out))
    out = run('run_sdd.py', "12\n\n", '--graph')
    check("--graph prints the dependency graph", '->' in out and 'S.v' in out)


