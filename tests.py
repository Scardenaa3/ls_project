def test_book_values():
    print("2. Values of the book")
    # Example 4.30 (E -> TE' ...) with S = E, A = E', B = T'
    g = parse_grammar(["S -> TA", "A -> +TA e", "T -> FB", "B -> *FB e",
                       "F -> (S) i"])
    first = {a: format_set(g.first[a]) for a in g.nonterminals}
    follow = {a: format_set(g.follow[a]) for a in g.nonterminals}
    check("FIRST(S)=FIRST(T)=FIRST(F)={(, i}",
          first['S'] == first['T'] == first['F'] == '{(, i}', str(first))
    check("FIRST(A)={+, e} and FIRST(B)={*, e}",
          first['A'] == '{+, e}' and first['B'] == '{*, e}', str(first))
    check("FOLLOW(S)=FOLLOW(A)={), $}",
          follow['S'] == follow['A'] == '{), $}', str(follow))
    check("FOLLOW(T)=FOLLOW(B)={), +, $}",
          follow['T'] == follow['B'] == '{), +, $}', str(follow))
    check("FOLLOW(F)={), *, +, $}", follow['F'] == '{), *, +, $}', str(follow))
    l = LL1(g)
    check("Example 4.30 grammar is LL(1)", l.is_ll1)

    # Fig. 4.31: the expression grammar has 12 LR(0) states and is SLR(1)
    g = parse_grammar(["S -> S+T T", "T -> T*F F", "F -> (S) i"])
    s = SLR1(g)
    check("Fig. 4.31: 12 LR(0) states", len(s.states) == 12, str(len(s.states)))
    check("Expression grammar is SLR(1)", s.is_slr1)

    # Study guide, exercise B: 8 states; exercise D: reduce/reduce conflict
    g = parse_grammar(["S -> aSb A", "A -> cA e"])
    check("Exercise B: 8 LR(0) states", len(SLR1(g).states) == 8)
    g = parse_grammar(["S -> AaAb BbBa", "A -> e", "B -> e"])
    check("Exercise D: reduce/reduce conflict in SLR(1)",
          not SLR1(g).is_slr1 and LL1(g).is_ll1)


