def language(g, maxlen):
    """All strings of length <= maxlen derived with leftmost derivations."""
    nts = g.nt_set
    start = (g.start,)
    seen = {start}
    queue = deque([start])
    lang = set()
    bound = 2 * maxlen + 4
    while queue:
        form = queue.popleft()
        idx = next((i for i, x in enumerate(form) if x in nts), None)
        if idx is None:
            lang.add(''.join(form))
            continue
        for head, body in g.prods:
            if head != form[idx]:
                continue
            new = form[:idx] + tuple(body) + form[idx + 1:]
            terms = sum(1 for x in new if x not in nts)
            if terms > maxlen or len(new) > bound:
                continue
            if new not in seen:
                seen.add(new)
                queue.append(new)
    return lang


CROSS = [
    # name, lines, max length, LL(1)?, SLR(1)?
    ("S -> AB (statement, example 2)",
     ["S -> AB", "A -> aA d", "B -> bBc e"], 7, True, True),
    ("nested lists (report)",
     ["S -> [L] a", "L -> SM", "M -> ,SM e"], 7, True, True),
    ("a^n b^n", ["S -> aSb e"], 8, True, True),
    ("exercise A", ["S -> aSb A", "A -> cA e"], 7, True, True),
    ("exercise C (left recursion)", ["S -> S+T T", "T -> a"], 7, False, True),
    ("S -> Sa b", ["S -> Sa b"], 7, False, True),
    ("S -> aS e", ["S -> aS e"], 7, True, True),
    ("exercise D", ["S -> AaAb BbBa", "A -> e", "B -> e"], 4, True, False),
    ("digits (Item 3 grammar, 2 digits)",
     ["S -> L", "L -> DN", "N -> L e", "D -> 0 1"], 6, True, True),
    ("expressions", ["S -> S+T T", "T -> T*F F", "F -> (S) i"], 5, False, True),
    ("nullable chain", ["S -> ABC", "A -> aA e", "B -> bB e", "C -> cC e"],
     6, True, True),
]


def test_cross_check():
    print("4. Cross-check of the parsers against brute-force derivations")
    for name, lines, maxlen, exp_ll1, exp_slr in CROSS:
        g = parse_grammar(lines)
        ll1, slr = LL1(g), SLR1(g)
        check(f"{name}: LL(1)={exp_ll1}, SLR(1)={exp_slr}",
              ll1.is_ll1 == exp_ll1 and slr.is_slr1 == exp_slr,
              f"got LL(1)={ll1.is_ll1}, SLR(1)={slr.is_slr1}")
        lang = language(g, maxlen)
        parsers = []
        if ll1.is_ll1:
            parsers.append(('LL(1)', ll1))
        if slr.is_slr1:
            parsers.append(('SLR(1)', slr))
        for pname, parser in parsers:
            bad = []
            count = 0
            for n in range(maxlen + 1):
                for tup in itertools.product(g.terminals, repeat=n):
                    s = ''.join(tup)
                    count += 1
                    got, _, _ = parser.parse(s if s else 'e')
                    if got != (s in lang):
                        bad.append(s)
                        if len(bad) >= 3:
                            break
                if len(bad) >= 3:
                    break
            check(f"{name}: {pname} agrees on {count} strings "
                  f"({len(lang)} in the language)", not bad,
                  f"differs on {bad}")


def main():
    test_statement_examples()
    test_book_values()
    test_sdd()
    test_cross_check()
    print()
    print(f"{total - failures}/{total} checks passed")
    sys.exit(1 if failures else 0)


if __name__ == '__main__':
    main()
